--   ROW    = the tool's atlas_row (registry.lua): swords 0..5, pickaxes 6..11, shovels 12..17.
--   COLUMN = durability frame, 0 = full bar/green .. 10 = empty/red (update_durability_frame picks it).
-- Note the Stone tier's material id is 'cobblestone'.
SMODS.Atlas { key = 'bc_tools', path = 'tools.png', px = 71, py = 95 }

