-- Tool consumable type + the 18 tool cards (3 tools x 6 materials).
-- Tools are CRAFT-ONLY (shop_rate = 0) but DO appear in the collection (no_collection = false).
--
-- PERSISTENT, MULTI-USE items (not single-use): each tool has a durability budget
-- (ability.extra.uses_left/max_uses, base by material in registry.lua). Using a tool spends
-- one use and locks it for the rest of the blind (used_this_blind); at 0 uses it breaks
-- (start_dissolve). keep_on_use=true stops the engine from auto-consuming it. Per-tool state
-- lives on card.ability.extra (deep-copied per card, serialized natively -- no custom save/load).
--
-- Each card's use() writes per-blind / pending state onto G.GAME.balacraft (seeded in the
-- init_game_object wrapper in utilities/resources.lua):
--   sword   -> lower tiers (wood..gold) multiply G.GAME.balacraft.sword_xmult (flat X-Mult);
--              TOP tiers (diamond/netherite) instead add to G.GAME.balacraft.sword_exp, which
--              RAISES the hand Mult to a power during scoring (Talisman-safe) so they keep pace
--              with super-exponential late-game scores. Both applied via the lovely.toml patch,
--              reset each blind via reset_game_globals. Sharpness scales the X-mult on flat
--              swords, and deepens the exponent on top-tier swords.
--   pickaxe -> arms G.GAME.balacraft.mine_bonus (+N ore per Ore-Block card mined this blind)
--   shovel  -> arms G.GAME.balacraft.pending_shovel  (+$N on next blind defeated)
--              Fortune enchant adds a random 0..tier bonus to pickaxe/shovel payout.
-- The pending one-shots are consumed in PB_UTIL.grant_blind_drop (Blind:defeat wrapper).
-- Enchant math helpers (PB_UTIL.sharpness_mult / fortune_bonus) load with content/enhancements/
-- and are guarded here so tools still work when enhancements_enabled is off.
--
-- Depends on: PB_UTIL.TOOLS (content/tools/registry.lua) and the bc_resource_cards atlas
-- (content/resources/registry.lua) -- both load before this file (see main.lua).

