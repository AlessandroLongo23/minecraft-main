-- Tool consumable type + the 24 tool cards (4 tools: sword/pickaxe/shovel/axe x 6 materials).
-- Tools are CRAFT-ONLY (shop_rate = 0) but DO appear in the collection (no_collection = false).
--
-- PERSISTENT, MULTI-USE items (not single-use): each tool has a durability budget
-- (ability.extra.uses_left/max_uses, base by material in registry.lua). Using a tool always
-- spends one durability use; at 0 uses it breaks (start_dissolve). keep_on_use=true stops the
-- engine from auto-consuming it. Per-tool state lives on card.ability.extra (deep-copied per
-- card, serialized natively -- no custom save/load).
--   Once-per-blind lock: the sword, the shovel and the axe-as-WEAPON set used_this_blind and a
--   per-type lock so only one of each can act per blind. MINING actions are exempt and MULTI-USE
--   per blind -- the pickaxe (always) and the axe when chopping highlighted wood (is_mine_mode):
--   they still spend durability but never take the locks, so you can keep mining/chopping all blind.
--
-- Each card's use() writes per-blind / pending state onto G.GAME.balacraft (seeded in the
-- init_game_object wrapper in utilities/resources.lua):
--   sword   -> lower tiers (wood..gold) multiply G.GAME.balacraft.sword_xmult (flat X-Mult);
--              TOP tiers (diamond/netherite) instead add to G.GAME.balacraft.sword_exp, which
--              RAISES the hand Mult to a power during scoring (Talisman-safe) so they keep pace
--              with super-exponential late-game scores. Both applied via the lovely.toml patch,
--              reset each blind via reset_game_globals. Sharpness scales the X-mult on flat
--              swords, and deepens the exponent on top-tier swords.
--   pickaxe -> mines the Ore-Block cards highlighted in hand when Used, gated by the material's
--              mining level (PB_UTIL.can_mine); Fortune adds a random 0..tier bonus to each yield.
--   shovel  -> arms G.GAME.balacraft.pending_shovel  (+$N on next blind defeated)
--              Fortune enchant raises the shovel's find odds.
--   axe     -> DUAL. With WOOD ore-block(s) highlighted: chops +`value` wood per card (may take
--              several at once). Used ALONE (no wood selected): a WEAPON -- arms the hybrid
--              axe_chips + axe_xmult buff for this blind (lovely.toml scoring patch).
--   The pickaxe/axe read G.hand.highlighted in use() (the same UX as applying a Tarot to selected
--   cards), so no extra UI is needed. PB_UTIL.oreblock_ore / can_mine / revert_oreblock_card come
--   from utilities/card_enhancements.lua + content/resources/registry.lua (guarded if absent).
-- The pending one-shots are consumed in PB_UTIL.grant_blind_drop (Blind:defeat wrapper).
-- Enchant math helpers (PB_UTIL.sharpness_mult / fortune_bonus) load with content/enhancements/
-- and are guarded here so tools still work when enhancements_enabled is off.
--
-- Depends on: PB_UTIL.TOOLS (content/tools/registry.lua) and the bc_resource_cards atlas
-- (content/resources/registry.lua) -- both load before this file (see main.lua).

