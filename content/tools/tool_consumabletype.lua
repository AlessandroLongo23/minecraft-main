-- center key -> badge cell in bc_tool_icons, for the crafting recipe list & output preview
-- (crafting_ui.lua). Non-tool consumables (e.g. Torch) are absent and fall back to card art.
PB_UTIL.tool_icon_pos = {}
for id, a in pairs(ART) do
    if a.icon_pos then PB_UTIL.tool_icon_pos['c_balacraft_tool_' .. id] = a.icon_pos end
